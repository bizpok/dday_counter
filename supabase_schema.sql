-- 1. dodo_project 공유 회원 프로필 테이블 (public.profiles) 확인
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email TEXT,
  username TEXT UNIQUE,
  full_name TEXT,
  avatar_url TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. 사용자별 기념일 테이블 (public.dday_anniversaries)
CREATE TABLE IF NOT EXISTS public.dday_anniversaries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
  title TEXT NOT NULL,
  target_date DATE NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.dday_anniversaries
  ADD COLUMN IF NOT EXISTS user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid();

CREATE INDEX IF NOT EXISTS idx_dday_anniversaries_user_id ON public.dday_anniversaries(user_id);

-- 3. 사용자별 결심 테이블 (public.dday_resolutions)
CREATE TABLE IF NOT EXISTS public.dday_resolutions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
  title TEXT NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  check_logs JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.dday_resolutions
  ADD COLUMN IF NOT EXISTS user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid();

ALTER TABLE public.dday_resolutions
  ADD COLUMN IF NOT EXISTS check_logs JSONB NOT NULL DEFAULT '{}'::jsonb;

CREATE INDEX IF NOT EXISTS idx_dday_resolutions_user_id ON public.dday_resolutions(user_id);

-- 기존 user_id IS NULL 데이터를 최초 가입 회원(dodo_project 공유 계정)에 자동 연결
DO $$
DECLARE
  v_first_user UUID;
BEGIN
  SELECT id INTO v_first_user FROM auth.users ORDER BY created_at ASC LIMIT 1;
  IF v_first_user IS NOT NULL THEN
    UPDATE public.dday_anniversaries SET user_id = v_first_user WHERE user_id IS NULL;
    UPDATE public.dday_resolutions SET user_id = v_first_user WHERE user_id IS NULL;
  END IF;
END;
$$;

-- 4. Row Level Security (RLS) - 본인(auth.uid() = user_id) 데이터만 접근 허용
ALTER TABLE public.dday_anniversaries ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.dday_resolutions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public all on dday_anniversaries" ON public.dday_anniversaries;
DROP POLICY IF EXISTS "Users can view own dday_anniversaries" ON public.dday_anniversaries;
DROP POLICY IF EXISTS "Users can insert own dday_anniversaries" ON public.dday_anniversaries;
DROP POLICY IF EXISTS "Users can update own dday_anniversaries" ON public.dday_anniversaries;
DROP POLICY IF EXISTS "Users can delete own dday_anniversaries" ON public.dday_anniversaries;

CREATE POLICY "Users can view own dday_anniversaries"
  ON public.dday_anniversaries FOR SELECT TO authenticated
  USING (auth.uid() = user_id);

CREATE POLICY "Users can insert own dday_anniversaries"
  ON public.dday_anniversaries FOR INSERT TO authenticated
  WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can update own dday_anniversaries"
  ON public.dday_anniversaries FOR UPDATE TO authenticated
  USING (auth.uid() = user_id)
  WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can delete own dday_anniversaries"
  ON public.dday_anniversaries FOR DELETE TO authenticated
  USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Allow public all on dday_resolutions" ON public.dday_resolutions;
DROP POLICY IF EXISTS "Users can view own dday_resolutions" ON public.dday_resolutions;
DROP POLICY IF EXISTS "Users can insert own dday_resolutions" ON public.dday_resolutions;
DROP POLICY IF EXISTS "Users can update own dday_resolutions" ON public.dday_resolutions;
DROP POLICY IF EXISTS "Users can delete own dday_resolutions" ON public.dday_resolutions;

CREATE POLICY "Users can view own dday_resolutions"
  ON public.dday_resolutions FOR SELECT TO authenticated
  USING (auth.uid() = user_id);

CREATE POLICY "Users can insert own dday_resolutions"
  ON public.dday_resolutions FOR INSERT TO authenticated
  WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can update own dday_resolutions"
