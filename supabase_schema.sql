CREATE TABLE IF NOT EXISTS public.dday_anniversaries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  target_date DATE NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.dday_resolutions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.dday_anniversaries ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.dday_resolutions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public all on dday_anniversaries" ON public.dday_anniversaries;
CREATE POLICY "Allow public all on dday_anniversaries"
  ON public.dday_anniversaries
  FOR ALL
  USING (true)
  WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public all on dday_resolutions" ON public.dday_resolutions;
CREATE POLICY "Allow public all on dday_resolutions"
  ON public.dday_resolutions
  FOR ALL
  USING (true)
  WITH CHECK (true);
